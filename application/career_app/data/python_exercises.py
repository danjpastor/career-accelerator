def exercise_number_for_label(label):
    text = str(label or "").strip()
    for number, item in PYTHON_EXERCISES.items():
        if text == item["label"]:
            return number
    match = re.search(r"Python Exercise\s+(\d+)", text, re.IGNORECASE)
    return int(match.group(1)) if match and int(match.group(1)) in PYTHON_EXERCISES else None


def exercise_for_label(label):
    number = exercise_number_for_label(label)
    return PYTHON_EXERCISES.get(number) if number is not None else None
